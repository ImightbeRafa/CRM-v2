/**
 * Chat Phase 4 local Postgres micro-benchmarks.
 *
 *   CHAT_SCALE_DATABASE_URL=postgresql://...@127.0.0.1:5432/... \
 *     npx tsx scripts/chat-scale-benchmark.ts
 *
 * Measures p50/p95 for:
 *   a) conversation list ORDER BY lastMessageAt DESC LIMIT 30
 *   b) changes?afterRevision=head idle (revision > max → empty)
 * Runs EXPLAIN (ANALYZE, BUFFERS) and asserts expected index usage.
 * Writes docs/audits/chat-phase4-scale-report.md (+ .json beside it).
 */
import { mkdirSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import postgres from 'postgres'
import { SCALE_TENANT_ID } from './lib/chat-scale-constants'
import {
  requireChatScaleDatabaseUrl,
  summarizeLatencies,
} from './lib/chat-scale-db-guard'

const ITERATIONS = Number(process.env.CHAT_SCALE_BENCH_ITERS || 40)
const WARMUP = Number(process.env.CHAT_SCALE_BENCH_WARMUP || 5)
const LIST_LIMIT = 30
const CHANGES_LIMIT = 100
const CONVERSATION_MIN = 100

const REPORT_MD = join(
  dirname(fileURLToPath(import.meta.url)),
  '..',
  'docs',
  'audits',
  'chat-phase4-scale-report.md',
)
const REPORT_JSON = join(
  dirname(fileURLToPath(import.meta.url)),
  '..',
  'docs',
  'audits',
  'chat-phase4-scale-report.json',
)

const LIST_SQL = `
SELECT id, "tenantId", "socialAccountId", "peerId", status,
       "lastMessageAt", "lastMessagePreview", revision
FROM public."ChatConversation"
WHERE "tenantId" = $1
ORDER BY "lastMessageAt" DESC, id DESC
LIMIT ${LIST_LIMIT}
`

const CHANGES_SQL = `
SELECT id, "tenantId", revision, "lastMessageAt"
FROM public."ChatConversation"
WHERE "tenantId" = $1 AND revision > $2::bigint
ORDER BY revision ASC
LIMIT ${CHANGES_LIMIT}
`

function usesExpectedIndex(planText: string, needle: string): boolean {
  const lower = planText.toLowerCase()
  return (
    lower.includes(needle.toLowerCase()) &&
    /index (only )?scan|bitmap index scan/i.test(planText)
  )
}

async function timeQuery(
  sql: postgres.Sql,
  label: string,
  run: () => Promise<unknown>,
): Promise<number[]> {
  for (let i = 0; i < WARMUP; i++) await run()
  const samples: number[] = []
  for (let i = 0; i < ITERATIONS; i++) {
    const t0 = performance.now()
    await run()
    samples.push(performance.now() - t0)
  }
  console.log(`${label}:`, summarizeLatencies(samples))
  return samples
}

async function explain(
  sql: postgres.Sql,
  query: string,
  params: unknown[],
): Promise<string> {
  const rows = await sql.unsafe(
    `EXPLAIN (ANALYZE, BUFFERS, FORMAT TEXT) ${query}`,
    params as (string | number | boolean | null)[],
  )
  return rows
    .map((r: { 'QUERY PLAN'?: string }) => r['QUERY PLAN'] || String(Object.values(r)[0]))
    .join('\n')
}

function renderReport(args: {
  ranAt: string
  host: string
  port: string
  counts: { accounts: number; conversations: number; messages: number }
  list: ReturnType<typeof summarizeLatencies>
  changes: ReturnType<typeof summarizeLatencies>
  listExplain: string
  changesExplain: string
  listIndexOk: boolean
  changesIndexOk: boolean
  idlePayloadBytes: number
}): string {
  return `# Chat Phase 4 — scale report

> Generated by \`scripts/chat-scale-benchmark.ts\` at **${args.ranAt}**
> Target: \`${args.host}:${args.port}\` · tenant \`${SCALE_TENANT_ID}\`

## Seed counts

| Entity | Count |
|---|---|
| SocialAccounts | ${args.counts.accounts} |
| ChatConversations | ${args.counts.conversations} |
| ChatMessages | ${args.counts.messages} |

## Latency (ms)

| Query | n | p50 | p95 | min | max | mean |
|---|---:|---:|---:|---:|---:|---:|
| List \`LIMIT 30\` (4.1) | ${args.list.count} | ${args.list.p50Ms.toFixed(2)} | ${args.list.p95Ms.toFixed(2)} | ${args.list.minMs.toFixed(2)} | ${args.list.maxMs.toFixed(2)} | ${args.list.meanMs.toFixed(2)} |
| Changes idle head (4.2) | ${args.changes.count} | ${args.changes.p50Ms.toFixed(2)} | ${args.changes.p95Ms.toFixed(2)} | ${args.changes.minMs.toFixed(2)} | ${args.changes.maxMs.toFixed(2)} | ${args.changes.meanMs.toFixed(2)} |

Idle changes approximate payload size: **${args.idlePayloadBytes} bytes**.

## Index assertions

| Query | Expected index | Observed |
|---|---|---|
| List | \`ChatConversation_tenantId_lastMessageAt_id_idx\` | ${args.listIndexOk ? 'PASS' : 'FAIL'} |
| Changes | \`ChatConversation_tenantId_revision_idx\` | ${args.changesIndexOk ? 'PASS' : 'FAIL'} |

## Acceptance table (4.1–4.7)

| # | Criterion | Target | Measured | Status |
|---|---|---|---|---|
| 4.1 | List p95 + index | p95 < 150 ms; uses \`(tenantId, lastMessageAt)\` | p95=${args.list.p95Ms.toFixed(2)} ms; index=${args.listIndexOk ? 'yes' : 'no'} | ${args.list.p95Ms < 150 && args.listIndexOk ? 'PASS' : 'FAIL'} |
| 4.2 | Changes idle p95 + payload | p95 < 60 ms; payload < 1 KB | p95=${args.changes.p95Ms.toFixed(2)} ms; ${args.idlePayloadBytes} B; index=${args.changesIndexOk ? 'yes' : 'no'} | ${args.changes.p95Ms < 60 && args.idlePayloadBytes < 1024 && args.changesIndexOk ? 'PASS' : 'FAIL'} |
| 4.3 | 3k-thread first paint window | ≤ 100 msgs / page | pending UI harness | pending |
| 4.4 | Idle network ≤ 1 req / 5 s | \`CHAT_INBOX_V2_POLL_MS ≤ 5000\` | see \`chat-idle-network-assert\` | pending / unit |
| 4.5 | 500 webhooks / 60 s | 0 dups, 0 429s, p95 < 800 ms | see \`chat-webhook-burst\` | pending / unit |
| 4.6 | Template cache | 1 Graph call / 5 min | not in this slice | pending |
| 4.7 | Soft AI delivery key | exactly-once outbound | needs ChatAutomationJob | pending |

## EXPLAIN — list

\`\`\`
${args.listExplain}
\`\`\`

## EXPLAIN — changes idle

\`\`\`
${args.changesExplain}
\`\`\`
`
}

async function main() {
  const guard = requireChatScaleDatabaseUrl()
  const sql = postgres(guard.url, {
    max: 2,
    prepare: false,
    ssl: false,
    connect_timeout: 15,
  })

  try {
    const [acct] =
      await sql`SELECT COUNT(*)::int AS n FROM public."SocialAccount" WHERE "tenantId" = ${SCALE_TENANT_ID}`
    const [conv] =
      await sql`SELECT COUNT(*)::int AS n FROM public."ChatConversation" WHERE "tenantId" = ${SCALE_TENANT_ID}`
    const [msg] =
      await sql`SELECT COUNT(*)::int AS n FROM public."ChatMessage" WHERE "tenantId" = ${SCALE_TENANT_ID}`

    if (!conv?.n || conv.n < CONVERSATION_MIN) {
      console.error(
        `Insufficient seed data for tenant ${SCALE_TENANT_ID} ` +
          `(conversations=${conv?.n ?? 0}). Run chat:scale:seed first.`,
      )
      process.exit(1)
    }

    const [headRow] = await sql`
      SELECT COALESCE(MAX(revision), 0)::text AS head
      FROM public."ChatConversation"
      WHERE "tenantId" = ${SCALE_TENANT_ID}
    `
    const headRevision = headRow?.head ?? '0'

    const listSamples = await timeQuery(sql, 'list', async () => {
      await sql.unsafe(LIST_SQL, [SCALE_TENANT_ID])
    })

    const changesSamples = await timeQuery(sql, 'changes-idle', async () => {
      await sql.unsafe(CHANGES_SQL, [SCALE_TENANT_ID, headRevision])
    })

    const idleRows = await sql.unsafe(CHANGES_SQL, [SCALE_TENANT_ID, headRevision])
    const idlePayloadBytes = Buffer.byteLength(
      JSON.stringify({ conversations: idleRows }),
      'utf8',
    )

    const listExplain = await explain(sql, LIST_SQL, [SCALE_TENANT_ID])
    const changesExplain = await explain(sql, CHANGES_SQL, [
      SCALE_TENANT_ID,
      headRevision,
    ])

    const listIndexOk = usesExpectedIndex(
      listExplain,
      'ChatConversation_tenantId_lastMessageAt_id_idx',
    )
    const changesIndexOk = usesExpectedIndex(
      changesExplain,
      'ChatConversation_tenantId_revision_idx',
    )

    if (!listIndexOk) {
      console.error(
        'FAIL: list EXPLAIN did not use ChatConversation_tenantId_lastMessageAt_id_idx',
      )
    }
    if (!changesIndexOk) {
      console.error(
        'FAIL: changes EXPLAIN did not use ChatConversation_tenantId_revision_idx',
      )
    }

    const list = summarizeLatencies(listSamples)
    const changes = summarizeLatencies(changesSamples)
    const ranAt = new Date().toISOString()
    const counts = {
      accounts: acct?.n ?? 0,
      conversations: conv?.n ?? 0,
      messages: msg?.n ?? 0,
    }

    const payload = {
      ranAt,
      host: guard.hostname,
      port: guard.port,
      tenantId: SCALE_TENANT_ID,
      counts,
      list,
      changes,
      idlePayloadBytes,
      listIndexOk,
      changesIndexOk,
      listExplain,
      changesExplain,
    }

    mkdirSync(dirname(REPORT_MD), { recursive: true })
    writeFileSync(REPORT_JSON, `${JSON.stringify(payload, null, 2)}\n`, 'utf8')
    writeFileSync(
      REPORT_MD,
      renderReport({
        ranAt,
        host: guard.hostname,
        port: guard.port,
        counts,
        list,
        changes,
        listExplain,
        changesExplain,
        listIndexOk,
        changesIndexOk,
        idlePayloadBytes,
      }),
      'utf8',
    )

    console.log(`wrote ${REPORT_MD}`)
    console.log(`wrote ${REPORT_JSON}`)

    if (!listIndexOk || !changesIndexOk) process.exit(2)
  } finally {
    await sql.end({ timeout: 5 })
  }
}

main().catch((err) => {
  console.error('chat-scale-benchmark failed:', err)
  process.exit(1)
})
