  /**
   * Generate multiple guías in sequence
   */
  async generateMultipleGuias(orders: OrderData[]): Promise<GuiaResult[]> {
    const results: GuiaResult[] = [];

    try {
      await this.initialize();
      await this.login();
      await this.navigateToGuiaCreation();
      
      // Create guías for all orders
      for (let i = 0; i < orders.length; i++) {
        const order = orders[i];
        console.log(`Processing order ${i + 1}/${orders.length}: ${order.orderId}`);

        const result = await this.fillGuiaForm(order);
        results.push(result);

        // Handle "crear otra guía" dialog
        if (i < orders.length - 1) {
          // More orders to process, click "Sí, crear otra guía"
          await this.handleCreateAnotherDialog(true);
        } else {
          // Last order, go to list page to download PDFs
          console.log('✓ All guías created, going to download page...');
          await this.handleCreateAnotherDialog(false); // Click "Ver mis Guías"
        }
      }

      // Now on the guías list page - dismiss any popups and download PDFs
      console.log('On guías list page, dismissing popups...');
      await this.dismissListPagePopup();
      
      console.log('Downloading PDFs...');
      for (const result of results) {
        if (result.success && result.guiaNumber) {
          const order = orders.find(o => o.orderId === result.orderId);
          if (order) {
            const pdfResult = await this.downloadGuiaPDF(order.customerName);
            result.pdfDownloaded = pdfResult.success;
            if (pdfResult.success && pdfResult.buffer) {
              result.pdfBuffer = pdfResult.buffer;
              result.pdfFileName = pdfResult.fileName;
              console.log(`✓ PDF captured for ${order.customerName}: ${pdfResult.buffer.length} bytes`);
            }
            await new Promise(resolve => setTimeout(resolve, 1000));
          }
        }
      }

      await this.close();
      return results;

    } catch (error) {
      console.error('Error in generateMultipleGuias:', error);
      await this.close();
      return results.length > 0 ? results : [{
        success: false,
        error: `Failed to generate guías: ${error}`,
        orderId: 'BATCH'
      }];
    }
  }

