  /**
   * Extract guía number from the page after creation
   */
  private async extractGuiaNumber(): Promise<string | null> {
    if (!this.page) return null;

    try {
      // The guía number should be visible in the "¿Deseas crear otra guía?" dialog
      // Wait for it to appear
      await new Promise(resolve => setTimeout(resolve, 500));
      
      // Take a screenshot to debug
      await this.captureScreenshot('guia-created');
      
      // Look for guía number in the page
      const guiaInfo = await this.page.evaluate(() => {
        const bodyText = document.body.textContent || '';
        
        console.log('Page text for guía extraction:', bodyText.substring(0, 500));
        
        // Look for the guía number in the success dialog or page
        // Common patterns: PY05869748CR, 10823199, etc.
        const patterns = [
          /PY\d{8,10}CR/i,  // PY########CR format
          /\bPY\d{8,10}\b/i,  // PY######## without CR
          /Guía[:\s#]*(\d{7,10})/i,
          /Número[:\s]+(\d{7,10})/i,
          /Guide[:\s#]+(\d{7,10})/i,
          /creada[:\s]+(\d{7,10})/i,
          /exitosamente[:\s]+(\d{7,10})/i
        ];

        for (const pattern of patterns) {
          const match = bodyText.match(pattern);
          if (match) {
            const number = match[1] || match[0];
            // Skip if it looks like a postal code (5 digits) or phone (8 digits starting with specific patterns)
            if (!/^\d{5}$/.test(number) && !/^[67]\d{7}$/.test(number)) {
              console.log('Found guía number with pattern:', pattern, '→', number);
              return number.trim();
            }
          }
        }

        // Also check for any number in the dialog title, header, or success message
        const elements = Array.from(document.querySelectorAll('h1, h2, h3, h4, .modal-title, .dialog-title, .alert-success, .text-success, strong, b'));
        for (const element of elements) {
          const text = element.textContent || '';
          const match = text.match(/\d{7,10}/);
          if (match && !/^\d{5}$/.test(match[0]) && !/^[67]\d{7}$/.test(match[0])) {
            console.log('Found guía number in element:', element.tagName, '→', match[0]);
            return match[0];
          }
        }

        return null;
      });

      if (guiaInfo) {
        console.log(`✓ Extracted guía number: ${guiaInfo}`);
        return guiaInfo;
      }

      console.warn('⚠ Could not extract guía number from page');
      return null;
    } catch (error) {
      console.warn('Failed to extract guía number:', error);
      return null;
    }
  }

