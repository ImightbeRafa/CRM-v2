  /**
   * Download PDF from the guías list page and return buffer
   */
  private async downloadGuiaPDF(customerName: string): Promise<{ success: boolean; buffer?: Buffer; fileName?: string }> {
    if (!this.page) return { success: false };

    try {
      console.log(`Looking for PDF download button for customer: ${customerName}`);
      
      // Wait for the table to load
      await this.page.waitForSelector('table, tr', { timeout: 5000 }).catch(() => {});
      await new Promise(resolve => setTimeout(resolve, 1000));

      // Take a screenshot to debug
      await this.captureScreenshot('guias-list');

      // Find the download URL first
      const downloadInfo = await this.page.evaluate((name) => {
        const normalizeText = (text: string) => {
          return text.normalize('NFD').replace(/[\u0300-\u036f]/g, '').toLowerCase().trim();
        };
        
        const searchName = normalizeText(name);
        const rows = Array.from(document.querySelectorAll('tr'));
        
        console.log(`Searching for customer: ${name} (normalized: ${searchName})`);
        console.log(`Found ${rows.length} rows`);
        
        for (const row of rows) {
          const rowText = normalizeText(row.textContent || '');
          if (rowText.includes(searchName)) {
            console.log('Found matching row:', row.textContent?.substring(0, 100));
            
            // Look for PDF download link
            const downloadBtn = row.querySelector('a[href*="/guide/pdf/"], a[href*="/pdf/"]') as HTMLAnchorElement;
            if (downloadBtn) {
              console.log('Found download button:', downloadBtn.href);
              return { success: true, href: downloadBtn.href };
            } else {
              console.log('No download button in row');
              return { success: false, error: 'Download button not found in row' };
            }
          }
        }
        
        return { success: false, error: 'Customer row not found' };
      }, customerName);

      if (!downloadInfo.success || !downloadInfo.href) {
        console.warn(`❌ Could not find PDF: ${downloadInfo.error}`);
        return { success: false };
      }

      console.log(`✓ Found PDF URL: ${downloadInfo.href}`);

      // Download the PDF using fetch in the browser context
      const pdfData = await this.page.evaluate(async (url) => {
        try {
          const response = await fetch(url, {
            method: 'GET',
            credentials: 'include', // Include cookies for authentication
            headers: {
              'Accept': 'application/pdf'
            }
          });
          
          if (!response.ok) {
            return { success: false, error: `HTTP ${response.status}` };
          }
          
          const arrayBuffer = await response.arrayBuffer();
          const bytes = Array.from(new Uint8Array(arrayBuffer));
          return { success: true, bytes };
        } catch (error: any) {
          return { success: false, error: error.message };
        }
      }, downloadInfo.href);

      if (!pdfData.success || !pdfData.bytes) {
        console.warn(`❌ Failed to fetch PDF: ${pdfData.error}`);
        return { success: false };
      }

      // Convert byte array back to Buffer
      const buffer = Buffer.from(pdfData.bytes);
      
      // Extract filename from URL or use default
      const fileName = `guia-${customerName.replace(/\s+/g, '-')}-${Date.now()}.pdf`;
      
      console.log(`✓ Downloaded PDF: ${buffer.length} bytes`);
      
      return { success: true, buffer, fileName };
    } catch (error) {
      console.warn('Failed to download PDF:', error);
      return { success: false };
    }
  }

