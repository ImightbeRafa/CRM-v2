  private async captureScreenshot(name: string, options: { fullPage?: boolean } = {}): Promise<void> {
    if (!this.page || !this.debugMode) {
      return;
    }

    const safeName = name.replace(/[^a-z0-9-_]/gi, '_').toLowerCase();
    const timestamp = Date.now();
    const filePath = `${safeName}-${timestamp}.png`;

    try {
      await this.page.screenshot({
        path: filePath as `${string}.png`,
        fullPage: options.fullPage ?? false
      });
      console.log(`Debug screenshot saved: ${filePath}`);
    } catch (error) {
      console.warn(`Failed to capture screenshot (${filePath}):`, error);
    }
  }
