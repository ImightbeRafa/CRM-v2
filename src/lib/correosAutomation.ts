  /**
   * Helper method to select from dropdown by visible text
   */
  private async selectDropdownByText(page: Page, selectSelector: string, optionText: string): Promise<boolean> {
    try {
      await page.waitForSelector(selectSelector, { timeout: 5000 });
      
      // Ensure optionText is a string
      const searchText = String(optionText || '').trim();
      if (!searchText) {
        console.warn('Empty option text provided to selectDropdownByText');
        return false;
      }
      
      // Normalize text for comparison (remove accents)
      const normalizeText = (text: string) => {
        return text.normalize('NFD').replace(/[\u0300-\u036f]/g, '').toLowerCase();
      };
      
      // Get all options
      const options = await page.$$eval(`${selectSelector} option`, (opts, text) => {
        const normalizeText = (str: string) => {
          return str.normalize('NFD').replace(/[\u0300-\u036f]/g, '').toLowerCase().trim();
        };
        const searchNormalized = normalizeText(String(text));
        
        // Map all options
        const allOptions = opts.map(opt => ({
          value: opt.value,
          text: opt.textContent?.trim() || '',
          normalized: normalizeText(opt.textContent?.trim() || '')
        }));
        
        // Filter options - exclude empty values and placeholder text
        return allOptions
          .filter(opt => {
            // Skip empty values
            if (opt.value === '' || opt.value === '0') return false;
            
            // Skip placeholder text (Spanish)
            const placeholders = [
              'seleccione',
              'selecciona',
              'seleccionar',
              'select'
            ];
            const textLower = opt.normalized;
            if (placeholders.some(ph => textLower.startsWith(ph))) return false;
            
            return true;
          })
          .filter(opt => {
            // Exact match first
            if (opt.normalized === searchNormalized) return true;
            // Then check if option text contains search or vice versa
            return opt.normalized.includes(searchNormalized) || searchNormalized.includes(opt.normalized);
          })
          .map(opt => ({ value: opt.value, text: opt.text })); // Remove normalized field
      }, searchText);

      if (options.length > 0) {
        console.log(`Found ${options.length} matching options, selecting: ${options[0].text} (value: ${options[0].value})`);
        
        // Set the value directly and trigger change events
        const result = await page.evaluate((selector, value, text) => {
          const element = document.querySelector(selector) as HTMLSelectElement;
          if (!element) {
            return { success: false, error: 'Element not found' };
          }
          
          // Check if the option exists
          const option = Array.from(element.options).find(opt => opt.value === value);
          if (!option) {
            return { success: false, error: `Option with value "${value}" not found in select` };
          }
          
          // Focus the element
          element.focus();
          
          // Set the value
          element.value = value;
          
          // Also set selectedIndex for good measure
          element.selectedIndex = Array.from(element.options).indexOf(option);
          
          // Trigger all necessary events in the right order
          element.dispatchEvent(new Event('input', { bubbles: true }));
          element.dispatchEvent(new Event('change', { bubbles: true }));
          element.dispatchEvent(new Event('blur', { bubbles: true }));
          
          // Verify the value was set
          const actualValue = element.value;
          return { 
            success: actualValue === value, 
            actualValue,
            expectedValue: value
          };
        }, selectSelector, options[0].value, options[0].text);
        
        if (result.success) {
          console.log(`✓ Selected "${options[0].text}" from dropdown (verified)`);
          await new Promise(resolve => setTimeout(resolve, 1000)); // Wait for any onChange handlers and cascading updates
          return true;
        } else {
          console.warn(`✗ Failed to select dropdown: ${result.error || 'Value mismatch'}`);
          if (result.actualValue !== undefined) {
            console.warn(`  Expected: ${result.expectedValue}, Got: ${result.actualValue}`);
          }
          return false;
        }
      }
      
      console.warn(`No matching option found for: ${searchText}`);
      return false;
    } catch (error) {
      console.warn(`Failed to select from dropdown: ${error}`);
      return false;
    }
  }

  /**
   * Fill sender (remitente) information
   */
  private async fillSenderInfo(): Promise<void> {
    if (!this.page || !this.senderInfo) return;

    console.log('Filling sender (remitente) information...');
    const s = this.senderInfo;

    // ID Type dropdown
    await this.selectDropdownByText(
      this.page,
      'select[name*="idType"], select[id*="idType"], select[name*="tipoIdentificacion"]',
      s.idType
    );

    // ID Number
    await this.fillField('input[name*="idNumber"], input[id*="idNumber"], input[name*="numeroIdentificacion"]', s.idNumber);

    // Name
    await this.fillField('input[name*="senderName"], input[id*="senderName"], input[name*="nombreRemitente"]', s.name);

    // Phone
    await this.fillField('input[name*="senderPhone"], input[id*="senderPhone"], input[name*="telefonoRemitente"]', s.phone);

    // Email
    await this.fillField('input[name*="senderEmail"], input[id*="senderEmail"], input[name*="correoRemitente"]', s.email);

    // Province dropdown
    await this.selectDropdownByText(
      this.page,
      'select[name*="senderProvince"], select[id*="senderProvince"], select[name*="provinciaRemitente"]',
      s.province
    );

    await new Promise(resolve => setTimeout(resolve, 1000)); // Wait for canton dropdown to populate

    // Canton dropdown
    await this.selectDropdownByText(
      this.page,
      'select[name*="senderCanton"], select[id*="senderCanton"], select[name*="cantonRemitente"]',
      s.canton
    );

    await new Promise(resolve => setTimeout(resolve, 1000)); // Wait for district dropdown to populate

    // District dropdown
    await this.selectDropdownByText(
      this.page,
      'select[name*="senderDistrict"], select[id*="senderDistrict"], select[name*="distritoRemitente"]',
      s.district
    );

    // Postal Code
    await this.fillField('input[name*="senderPostalCode"], input[id*="senderPostalCode"], input[name*="codigoPostalRemitente"]', s.postalCode);

    // Address
    await this.fillField('textarea[name*="senderAddress"], input[name*="senderAddress"], textarea[name*="direccionRemitente"]', s.address);

    console.log('Sender information filled');
  }

